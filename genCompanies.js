/* 公司名模板：返回候选名称 */
function buildName(region, ind) {
  const r = Math.random();
  const z = (2 + Math.floor(Math.random() * 2)); // 字号 2-3 字
  let hao = '';
  const pool = [X1, X2];
  for (let i = 0; i < z; i++) {
    const arr = pool[i % 2];
    let c;
    do { c = arr[Math.floor(Math.random() * arr.length)]; } while (z === 2 && i === 1 && c === hao[0] && Math.random() < 0.8);
    hao += c;
  }
  const isField = Math.random() < 0.28; // 28% 领域型后缀（自带行业属性，如「餐饮管理有限公司」）
  const t = isField ? FIELD_TYPES[Math.floor(Math.random() * FIELD_TYPES.length)] : TYPES[Math.floor(Math.random() * TYPES.length)];
  const shopt = SHOP_TYPES[Math.floor(Math.random() * SHOP_TYPES.length)];
  const isShop = Math.random() < 0.08; // 8% 个体工商户
  if (isShop) {
    const tpl = Math.floor(Math.random() * 3);
    if (tpl === 0) return `重庆市${region}${hao}${shopt}`;
    if (tpl === 1) return `重庆${region}${hao}${shopt}`;
    return `${hao}${shopt}（重庆${region}）`;
  }
  if (isField) {
    /* 领域型后缀自带行业语义：不再叠加行业词，避免「餐饮服务餐饮管理有限公司」式冗余 */
    const tpl = Math.floor(Math.random() * 3);
    if (tpl === 0) return `重庆${hao}${t}`;
    if (tpl === 1) return `重庆市${region}${hao}${t}`;
    return `${hao}${t}（重庆${region}）`;
  }
  const tpl = Math.floor(Math.random() * 6);
  if (tpl === 0) return `重庆${hao}${ind}${t}`;
  if (tpl === 1) return `重庆市${region}${hao}${ind}${t}`;
  if (tpl === 2) return `${hao}${ind}（重庆）${t}`;
  if (tpl === 3) return `重庆${region}${hao}${t}`;
  if (tpl === 4) return `重庆市${region}${hao}${t}`;
  return `重庆${hao}${ind}有限公司`;
}

